export type ResourceType = "Food" | "Labor";

/**
 * A card in play. `defId` references a CardDefinition in
 * game/components/registry.ts — what the card actually does lives there,
 * as a bag of components, not here. See game/components/types.ts.
 */
export interface CardInstance {
  instanceId: string;
  defId: string;
  tapped: boolean;
}

/**
 * Every phase this game can be in. Each one is defined as its own module
 * under game/phases/ (name, label, and rules all in one place), and
 * game/phases/index.ts's TURN_PHASES array lists which of them are
 * actually active in the turn loop — comment a phase's entry out of that
 * array and it's fully disabled, nothing else to touch.
 *
 * v0 deviates from the design docs' rough turn-order guess
 * (Untap -> Upkeep -> Main -> Warfare -> End): Upkeep needs Food, but Food
 * is only generated by tapping Workers in Main. So here Main comes before
 * Upkeep (generate resources, then spend them), and Warfare comes after
 * Upkeep as a stub (no opponent modeled yet). Untap is instantaneous (no
 * choices) and folded into the End -> Draw transition rather than being
 * its own UI phase.
 *
 * "mulligan" is a pregame phase, not part of the turn cycle: it happens
 * before turn 1's Draw phase, and never recurs once the player is
 * satisfied and moves on. The player may repeat it (discard the whole
 * hand, redraw one fewer card each time) until only 1 card is left.
 */
export type Phase = "mulligan" | "draw" | "main" | "upkeep" | "warfare" | "end";

export interface PlayerState {
  deck: CardInstance[];
  hand: CardInstance[];
  lane: CardInstance[];
  graveyard: CardInstance[];
  resources: Record<ResourceType, number>;
  hasPlacedWorkerThisTurn: boolean;
}

/**
 * Rule-level toggles a future card/ability can flip on, rather than special-
 * casing its effect into the reducer per card. See design/Rules/Placement
 * Modifiers.md in the Obsidian vault for the game-design side of this.
 */
export interface GameModifiers {
  /** Lets the player choose the lane index when placing a worker, instead
   *  of it always going to the back (see PLACE_WORKER's `index`). */
  freeWorkerPlacement: boolean;
}

export interface GameState {
  turn: number;
  phase: Phase;
  modifiers: GameModifiers;
  player: PlayerState;
  /**
   * The opponent's board, mirrored on the other side of the table — a real,
   * independently-dealt PlayerState (their own deck, their own starting
   * hand), not placeholder data. Purely inert display data for now: no
   * reducer/phase logic reads or writes it after setup, since they don't
   * take real turns yet. See game/setup.ts.
   */
  opponent: PlayerState;
  /** Food deficit still needing sacrifices this upkeep, if any. */
  pendingSacrifices: number;
  log: string[];
  gameOver: boolean;
}

/**
 * ADVANCE is the one generic "move on" action ("Next" button, "End Turn",
 * etc.) — what it actually does depends entirely on which phase is active,
 * since each phase interprets it for itself (see game/phases/*.ts). The
 * other actions are genuine player choices distinct from "move on".
 */
export type Action =
  | { type: "CONFIRM_MULLIGAN" }
  | { type: "FINISH_MULLIGAN" }
  | { type: "PLACE_WORKER"; instanceId: string; index?: number }
  | { type: "TAP_WORKER"; instanceId: string }
  | { type: "SACRIFICE_WORKER"; instanceId: string }
  | { type: "ADVANCE" }
  | { type: "RESTART" };
